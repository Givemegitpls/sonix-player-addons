#!/usr/bin/env python3
"""Bake a bitmap font for the Gravity Defied addon.

The game was written against SDL_ttf: `Font` opened `FontSansSerif.ttf` at 12, 16
and 32 px, drew text with a colour, and asked the renderer for the width of a
string so that its menus could be laid out. On the device there is no SDL and no
FreeType in the addon, so the faces the game actually uses are rendered here,
once, into a C table of 8-bit coverage masks:

    gravity/platform/font_data.c        generated, committed

Run it from the addon's own directory after changing the source font or the list
of faces:

    python3 gravity/tools/bake_font.py

which renders `gravity/assets/FontSansSerif.ttf` (the font the upstream project
ships) for every (size, style) pair the game asks for, and warns about a pair it
does not have. Anti-aliased coverage is kept -- the game drew with
TTF_RenderText_Blended -- and `platform/font.cpp` blends it with the current
colour.

The output is a table, not a header: glyphs 32..126 (space to '~'), per face the
advance, the bearing and the top of each glyph relative to the baseline. Nothing
here runs at build time on a device or in CI; see gravity/NOTICE.md.
"""

from __future__ import annotations

import pathlib
import sys

try:
    from PIL import Image, ImageChops, ImageDraw, ImageFont
except ImportError:  # pragma: no cover
    sys.exit("bake_font: needs Pillow (python3 -m pip install pillow)")

HERE = pathlib.Path(__file__).resolve().parent
ADDON = HERE.parent
FONT = ADDON / "assets" / "FontSansSerif.ttf"
OUT = ADDON / "platform" / "font_data.c"

# What the game asks FontStorage for (grep FontStorage::getFont in game/src):
# 12 plain/bold, 16 plain/bold, 32 plain/bold. Italic is in the API and unused.
FACES = [(12, 0), (12, 1), (16, 0), (16, 1), (32, 0), (32, 1)]

FIRST, LAST = 32, 126


def bake(size: int, bold: int) -> dict:
    font = ImageFont.truetype(str(FONT), size)
    ascent, descent = font.getmetrics()

    glyphs = []
    pool = bytearray()
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        advance = int(round(font.getlength(ch)))

        # Render into a generous tile with the line's ascender box at (PAD, PAD),
        # so the baseline sits at PAD + ascent and every bearing is measured
        # from it.
        pad = size
        tile = Image.new("L", (advance + 2 * pad, size * 3), 0)
        ImageDraw.Draw(tile).text((pad, pad), ch, font=font, fill=255)
        box = tile.getbbox()
        if box is None:  # space: no ink, only an advance
            glyphs.append((advance, 0, 0, 0, 0, len(pool)))
            continue

        ink = tile.crop(box)
        if bold and ink.getbbox() is not None:
            # FontSansSerif.ttf has one weight; SDL_ttf faked bold with
            # TTF_SetFontStyle(STYLE_BOLD), so this does what that did -- the
            # glyph smeared one pixel to the right and given one more of
            # advance.
            wide = Image.new("L", (ink.width + 1, ink.height), 0)
            wide.paste(ink, (0, 0))
            shift = Image.new("L", (ink.width + 1, ink.height), 0)
            shift.paste(ink, (1, 0))
            ink = ImageChops.lighter(wide, shift)
            advance += 1
        left = box[0] - pad
        top = box[1] - pad - ascent
        w, h = ink.size
        data = ink.tobytes()
        glyphs.append((advance, left, top, w, h, len(pool)))
        pool += data

    return {
        "size": size,
        "bold": bold,
        "ascent": ascent,
        "descent": descent,
        "glyphs": glyphs,
        "pool": bytes(pool),
    }


def emit(faces: list[dict]) -> str:
    out = [
        "// Generated by gravity/tools/bake_font.py -- do not edit.",
        "//",
        "// The faces the game asks FontStorage for, rendered from",
        "// assets/FontSansSerif.ttf (the font the upstream project ships, GPL-2.0,",
        "// see NOTICE.md). 8-bit coverage, blended with the current colour by",
        "// platform/font.cpp.",
        "",
        '#include <stddef.h>',
        "",
        '#include "font_data.h"',
        "",
    ]

    for i, face in enumerate(faces):
        pool = face["pool"]
        out.append(f"static const uint8_t face{i}_coverage[{max(len(pool), 1)}] = {{")
        for off in range(0, len(pool), 16):
            row = ", ".join(str(b) for b in pool[off : off + 16])
            out.append(f"\t{row},")
        if not pool:
            out.append("\t0,")
        out.append("};")
        out.append(f"static const gd_glyph_t face{i}_glyphs[{LAST - FIRST + 1}] = {{")
        for advance, left, top, w, h, off in face["glyphs"]:
            out.append(f"\t{{ {advance}, {left}, {top}, {w}, {h}, {off} }},")
        out.append("};")
        out.append("")

    out.append("static const struct gd_face faces[] = {")
    for i, face in enumerate(faces):
        out.append(
            f'\t{{ {face["size"]}, {face["bold"]}, {face["ascent"]}, {face["descent"]}, '
            f"{face['ascent'] + face['descent']}, face{i}_glyphs, face{i}_coverage }},"
        )
    out.append("};")
    out.append("")
    out.append("const struct gd_face *gd_face_lookup(int size, int bold) {")
    out.append("\tfor (unsigned i = 0; i < sizeof(faces) / sizeof(faces[0]); i++) {")
    out.append("\t\tif (faces[i].size == size && faces[i].bold == (bold ? 1 : 0)) {")
    out.append("\t\t\treturn &faces[i];")
    out.append("\t\t}")
    out.append("\t}")
    out.append("\treturn NULL;")
    out.append("}")
    out.append("")
    return "\n".join(out)


def main() -> None:
    if not FONT.exists():
        sys.exit(f"bake_font: {FONT} is not there")

    faces = []
    for size, bold in FACES:
        face = bake(size, bold)
        ink = sum(g[3] * g[4] for g in face["glyphs"])
        print(
            f"bake_font: {size}px {'bold' if bold else 'plain'}: "
            f"{len(face['pool'])} bytes, ascent {face['ascent']}, descent {face['descent']}, "
            f"{ink} ink pixels"
        )
        faces.append(face)

    OUT.write_text(emit(faces))
    print(f"bake_font: wrote {OUT.relative_to(ADDON.parent)} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
