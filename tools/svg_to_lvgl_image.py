#!/usr/bin/env python3
"""Turn an SVG from the owner's drawing into an LVGL image for an addon.

The addons draw with LVGL objects, which cannot follow an arbitrary path -- and
a cassette hub is nothing but an arbitrary path. So the drawing is exported from
Blender as SVG, rasterised here at the size it is drawn at on the panel, and
compiled into the addon as an `lv_image_dsc_t`, exactly as Flappy Bird's
artwork is. Nothing is decoded at run time and nothing has to be found on the
card.

    python3 tools/svg_to_lvgl_image.py cassette-hub \\
        --svg "/home/me/cassette/tape_roller.svg" --size 50 \
        --tint "#e6e4e0" --out cassette/assets/hub.c

The picture keeps its alpha: what the SVG leaves transparent stays transparent,
so the black window behind a hub shows through the hub's keyed hole.

`--tint` recolours the whole picture, which is how one silhouette serves both
the light hubs of the reference and a hub in any other colour.
"""

import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile


def rasterise(svg, size, workdir):
    png = os.path.join(workdir, "raster.png")
    if shutil.which("rsvg-convert"):
        subprocess.run(["rsvg-convert", "-w", str(size), "-h", str(size), "-o", png, svg], check=True)
    elif shutil.which("magick"):
        subprocess.run(["magick", "-background", "none", "-density", "600", svg, "-resize", f"{size}x{size}", png],
                       check=True)
    else:
        sys.exit("svg_to_lvgl_image.py: needs rsvg-convert or ImageMagick")
    return png


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("name", help="C identifier of the image")
    ap.add_argument("--svg", required=True)
    ap.add_argument("--size", type=int, required=True, help="side of the square it is drawn in, in panel pixels")
    ap.add_argument("--tint", default=None, help="recolour the whole picture, #rrggbb")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    try:
        from PIL import Image
    except ImportError:
        sys.exit("svg_to_lvgl_image.py: needs Pillow (use /usr/bin/python3)")

    with tempfile.TemporaryDirectory() as tmp:
        png = rasterise(args.svg, args.size, tmp)
        im = Image.open(png).convert("RGBA")
        im = im.resize((args.size, args.size), Image.LANCZOS)

    if args.tint:
        t = args.tint.lstrip("#")
        tr, tg, tb = int(t[0:2], 16), int(t[2:4], 16), int(t[4:6], 16)
    else:
        tr = tg = tb = None

    ident = re.sub(r"[^0-9a-zA-Z_]", "_", args.name)
    w, h = im.size
    lines = [
        "// Generated by tools/svg_to_lvgl_image.py -- do not edit by hand.",
        f"// Source: {os.path.basename(args.svg)}, drawn at {w}x{h} px.",
        "#include \"lvgl/lvgl.h\"",
        "",
        f"static const uint8_t {ident}_map[] = {{",
    ]
    row = []
    for (r, g, b, a) in im.getdata():
        if tr is not None:
            # straight alpha: the tint replaces the colour, the alpha stays
            r, g, b = tr, tg, tb
        # LVGL stores ARGB8888 as B,G,R,A on a little-endian machine
        row.append(f"0x{b:02x},0x{g:02x},0x{r:02x},0x{a:02x}")
        if len(row) == 8:
            lines.append("\t" + ",".join(row) + ",")
            row = []
    if row:
        lines.append("\t" + ",".join(row) + ",")
    lines += [
        "};",
        "",
        f"const lv_image_dsc_t {ident} = {{",
        "\t.header.magic = LV_IMAGE_HEADER_MAGIC,",
        "\t.header.cf = LV_COLOR_FORMAT_ARGB8888,",
        f"\t.header.w = {w},",
        f"\t.header.h = {h},",
        f"\t.header.stride = {w * 4},",
        f"\t.data = {ident}_map,",
        f"\t.data_size = sizeof({ident}_map),",
        "};",
        "",
    ]
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {args.out} ({w}x{h}, {len(lines)} lines)")


if __name__ == "__main__":
    main()
